import time
import threading
from collections import deque
import psutil

class MetricsCollector:
    def __init__(self, history_maxlen=60, is_worker: bool = False):
        self.lock = threading.Lock()
        self.history_maxlen = history_maxlen
        self.is_worker = is_worker
        
        # Cumulative counters
        self.total_requests = 0
        self.successful_requests = 0
        self.failed_requests = 0
        
        # Sliding windows for real-time rates (last 5 seconds)
        self.recent_request_timestamps = deque()
        self.recent_latencies = deque(maxlen=200)
        
        # Synthetic workload factor (0.0 to 100.0) generated by load test / compute tasks
        self.synthetic_load = 0.0
        self.target_synthetic_load = 0.0
        
        # Time-series history for charts (1 sample per second)
        self.history = deque(maxlen=history_maxlen)
        self.last_real_cpu = None
        
        # Start background monitor thread for smoothing and recording history
        self._running = True
        self._monitor_thread = threading.Thread(target=self._background_sampler, daemon=True)
        self._monitor_thread.start()

    def record_request(self, latency_ms: float, success: bool = True):
        with self.lock:
            now = time.time()
            self.total_requests += 1
            if success:
                self.successful_requests += 1
            else:
                self.failed_requests += 1
            
            self.recent_request_timestamps.append(now)
            self.recent_latencies.append(latency_ms)

    def set_synthetic_load(self, load_percentage: float):
        """Set workload pressure from active load tests."""
        with self.lock:
            self.target_synthetic_load = max(0.0, min(100.0, float(load_percentage)))

    def get_current_metrics(self, current_replicas: int = 1):
        with self.lock:
            now = time.time()
            
            # Purge timestamps older than 3 seconds for RPS calculation
            window_seconds = 3.0
            cutoff = now - window_seconds
            while self.recent_request_timestamps and self.recent_request_timestamps[0] < cutoff:
                self.recent_request_timestamps.popleft()
            
            rps = round(len(self.recent_request_timestamps) / window_seconds, 1)
            
            # Latency calculation
            if self.recent_latencies:
                avg_latency = round(sum(self.recent_latencies) / len(self.recent_latencies), 1)
                sorted_lat = sorted(self.recent_latencies)
                p95_idx = int(len(sorted_lat) * 0.95)
                p95_latency = round(sorted_lat[min(p95_idx, len(sorted_lat) - 1)], 1)
            else:
                avg_latency = 4.2
                p95_latency = 8.5
            
            if self.is_worker:
                # In worker mode, report this machine's REAL CPU via psutil.cpu_percent
                if self.last_real_cpu is not None:
                    real_cpu = self.last_real_cpu
                else:
                    try:
                        real_cpu = psutil.cpu_percent(interval=None)
                    except Exception:
                        real_cpu = 0.0
                total_cpu = round(float(real_cpu), 1)
                scaled_latency = avg_latency
            else:
                # Baseline system CPU utilization
                try:
                    base_cpu = psutil.cpu_percent(interval=None)
                except Exception:
                    base_cpu = 12.0
                
                # Bounded base cpu range (10% - 25% idle)
                base_cpu = max(8.0, min(25.0, base_cpu))
                
                # Effective CPU per replica:
                # Synthetic load distributed across active replicas (Load balancing principle)
                replicas = max(1, current_replicas)
                workload_per_replica = self.synthetic_load / (replicas ** 0.85) # Diminishing returns scaling model
                
                total_cpu = min(100.0, round(base_cpu + workload_per_replica, 1))
                
                # Latency dynamically scales with CPU and inversely with replicas
                # Demonstrates that scaling out reduces latency congestion!
                if self.synthetic_load > 10:
                    congestion_factor = (total_cpu / 100.0) ** 2
                    scaled_latency = round(avg_latency + (congestion_factor * 85.0 / replicas), 1)
                else:
                    scaled_latency = avg_latency

            return {
                "cpu_utilization": total_cpu,
                "requests_per_second": rps,
                "average_latency_ms": scaled_latency,
                "p95_latency_ms": p95_latency,
                "total_requests": self.total_requests,
                "successful_requests": self.successful_requests,
                "failed_requests": self.failed_requests,
                "active_synthetic_load": round(self.synthetic_load, 1)
            }

    def _background_sampler(self):
        """Samples metrics once per second for time-series charts."""
        # Warmup psutil
        try:
            psutil.cpu_percent(interval=None)
        except Exception:
            pass

        while self._running:
            time.sleep(1.0)
            
            try:
                self.last_real_cpu = psutil.cpu_percent(interval=None)
            except Exception:
                pass

            # Smooth synthetic load towards target
            with self.lock:
                diff = self.target_synthetic_load - self.synthetic_load
                if abs(diff) < 2.0:
                    self.synthetic_load = self.target_synthetic_load
                else:
                    self.synthetic_load += diff * 0.35 # Responsive rise and decay

            # In worker mode, ScalingController loop is not running, so sampler pushes history points
            if self.is_worker:
                try:
                    curr = self.get_current_metrics(1)
                    self.push_history_point(curr, 1)
                except Exception:
                    pass

    def push_history_point(self, metrics: dict, replicas: int):
        with self.lock:
            now_str = time.strftime("%H:%M:%S")
            self.history.append({
                "time": now_str,
                "timestamp": int(time.time()),
                "cpu": metrics["cpu_utilization"],
                "replicas": replicas,
                "rps": metrics["requests_per_second"],
                "latency_ms": metrics["average_latency_ms"]
            })

    def get_history(self):
        with self.lock:
            return list(self.history)
